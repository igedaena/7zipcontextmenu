[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$projectRoot=Split-Path -Parent $PSScriptRoot
$identity=[Security.Principal.WindowsIdentity]::GetCurrent()
$principal=[Security.Principal.WindowsPrincipal]::new($identity)
if ($principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw 'Run this entry script normally so the post-install runtime test proves non-admin operation.' }
$adminScript=Join-Path $PSScriptRoot 'Invoke-PublicInstallerCycle.ps1'
$powershell=Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$process=Start-Process -FilePath $powershell -ArgumentList @('-NoProfile','-ExecutionPolicy','Bypass','-File',('"' + $adminScript + '"')) -Verb RunAs -WindowStyle Hidden -Wait -PassThru
if ($process.ExitCode -ne 0) { throw "Public installer cycle failed: $($process.ExitCode). See .tools\public-installer-admin-results.json" }
$admin=Get-Content -LiteralPath (Join-Path $projectRoot '.tools\public-installer-admin-results.json') -Raw | ConvertFrom-Json
if (-not $admin.Success) { throw $admin.Error }
$target=$admin.InstallRoot
$testRoot=Join-Path $projectRoot ('.review\public-runtime-' + [Guid]::NewGuid().ToString('N').Substring(0,8))
New-Item -ItemType Directory -Path $testRoot -Force | Out-Null
$source=Join-Path $testRoot 'sample.txt'
[IO.File]::WriteAllText($source,'public-install runtime fixture',[Text.UTF8Encoding]::new($false))
$requests=Join-Path ([Environment]::GetFolderPath('LocalApplicationData')) 'SevenZipContextMenu\Requests'
New-Item -ItemType Directory -Path $requests -Force | Out-Null
foreach ($architecture in @('x64','Win32')) {
    & (Join-Path $projectRoot ("build\$architecture\Release\host_menu_probe.exe")) $source
    if ($LASTEXITCODE -ne 0) { throw 'The public menu was not discovered.' }
    $before=@(Get-ChildItem -LiteralPath $requests -Filter '*.json' -File | Select-Object -ExpandProperty FullName)
    & (Join-Path $projectRoot ("build\$architecture\Release\shell_probe.exe")) --registered compress 1 $source
    if ($LASTEXITCODE -ne 0) { throw 'Public COM dispatch failed.' }
    $deadline=[DateTime]::UtcNow.AddSeconds(15); $new=$null
    do { $new=Get-ChildItem -LiteralPath $requests -Filter '*.json' -File | Where-Object { $_.FullName -notin $before } | Select-Object -First 1; if (-not $new) { Start-Sleep -Milliseconds 100 } } while (-not $new -and [DateTime]::UtcNow -lt $deadline)
    if (-not $new) { throw 'The public DLL did not create a user-local request.' }
    $diagnostic=Get-Content -LiteralPath $new.FullName -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($diagnostic.SelectedCount -ne 1 -or $diagnostic.SelectedPaths[0] -ne $source) { throw 'Public selection transfer was incorrect.' }
    Copy-Item -LiteralPath $new.FullName -Destination (Join-Path $testRoot ("diagnostic-$architecture.json"))
    Remove-Item -LiteralPath $new.FullName
}
$id=[Guid]::NewGuid().ToString('N'); $request=Join-Path $requests ($id+'.bin'); $result=Join-Path $testRoot 'runtime-result.json'
$writer=[IO.BinaryWriter]::new([IO.File]::Open($request,[IO.FileMode]::CreateNew,[IO.FileAccess]::Write),[Text.Encoding]::Unicode)
try { $writer.Write([uint32]0x31455a37); $writer.Write([uint32]3); $writer.Write([uint32]1); $writer.Write([uint32]$source.Length); $writer.Write([Text.Encoding]::Unicode.GetBytes($source)) } finally { $writer.Dispose() }
$runtime=Start-Process -FilePath (Join-Path $target 'SevenZipContextWorker.exe') -ArgumentList @('--headless','--request',('"'+$request+'"'),'--result',('"'+$result+'"')) -WindowStyle Hidden -Wait -PassThru
if ($runtime.ExitCode -ne 0) { throw 'The Program Files worker failed under a non-admin token.' }
$job=Get-Content -LiteralPath $result -Raw -Encoding UTF8 | ConvertFrom-Json
if (-not $job.Items[0].Success -or -not (Test-Path -LiteralPath $job.Items[0].Output)) { throw 'No archive was generated by the public runtime.' }
if (Test-Path -LiteralPath (Join-Path $target '.requests')) { throw 'Request data was written into Program Files.' }
[pscustomobject]@{Success=$true; PackageVersion='0.4.1'; InstallRoot=$target; InstallUninstallReinstall=$true; StandardUserRuntime=$true; RuntimeIsAdministrator=$false; PerUserRequestRoot=$requests; BothArchitectures=$true; Archive=$job.Items[0].Output; SettingsUiImplemented=$true; SettingsUiVerifiedInThisRun=$false} |
    ConvertTo-Json | Set-Content -LiteralPath (Join-Path $projectRoot '.tools\public-installer-test-results.json') -Encoding UTF8
Write-Output 'PASS: Program Files default, all-user install/remove/reinstall, both Shell architectures, and non-admin request/ZIP operation.'
